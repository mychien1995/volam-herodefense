import { z } from 'zod';
import type { SimulationConfig } from '@volam/game-core';
import { arena } from './arena.js';
const positive = z.number().finite().positive();
const count = z.number().int().nonnegative();
const projectile = z.strictObject({
  mode: z.literal('projectile'),
  damage: positive,
  speed: positive,
  range: positive,
  radius: positive,
  count: count.min(1).max(5),
  spacingTicks: count,
  splashRadius: z.number().nonnegative(),
  burnDamage: z.number().nonnegative(),
  burnTicks: count,
});
const arc = z.strictObject({
  mode: z.literal('arc'),
  damage: positive,
  range: positive,
  halfAngle: positive.max(Math.PI),
  cleave: z.number().min(0).max(1),
});
export const abilitySchema = z.strictObject({
  id: z.string().regex(/^[a-z_]+$/),
  nameVi: z.string().min(1),
  cooldownTicks: count.min(1),
  manaCost: z.number().nonnegative(),
  effect: z.discriminatedUnion('mode', [projectile, arc]),
});
const rect = z.strictObject({
  x: z.number().finite(),
  y: z.number().finite(),
  width: positive,
  height: positive,
});
const point = z.strictObject({
  x: z.number().finite(),
  y: z.number().finite(),
});
export const simulationConfigSchema = z.strictObject({
  tickRate: count.min(10).max(60),
  inputTimeoutTicks: count.min(1),
  width: positive,
  height: positive,
  collision: z.array(rect),
  spawn: point,
  creepSpawns: z.array(point).min(1),
  speed: positive,
  radius: positive,
  maxHp: positive,
  maxMana: positive,
  manaRegen: z.number().nonnegative(),
  hpPerLevel: z.number().nonnegative(),
  attackPerLevel: z.number().nonnegative(),
  xpPerLevel: count.min(1),
  maxLevel: z.literal(30),
  critChance: z.number().min(0).max(1),
  critMultiplier: positive,
  basics: z.record(z.string(), abilitySchema),
  skills: z.array(abilitySchema).length(2),
  creep: z.strictObject({
    hp: positive,
    defense: z.number().nonnegative(),
    speed: z.number().nonnegative(),
    radius: positive,
    damage: positive,
    attackRange: positive,
    detectionRange: positive,
    attackCooldownTicks: count.min(1),
    respawnTicks: count.min(30),
    xp: count,
    gold: count,
    assistTicks: count.min(1),
  }),
});
